        jdbcTemplate.update("INSERT INTO project_contributions (id, project_id, user_id, base_major_version, base_minor_version, approval_status, created_at) VALUES (202, 8, 99, 1, 1, 'APPROVED', CURRENT_TIMESTAMP)");
